"""جداکردن «محل» از «واحد» در همان رشتهٔ `org_unit`.

چرا این‌طور و نه یک ستون تازه
------------------------------
سازمانی که هم دفتر مرکزی دارد و هم کارخانه، «فروشِ کارخانه» و «فروشِ دفتر
مرکزی» را دو چیز می‌بیند — ولی `org_unit` یک رشتهٔ آزاد است و هر دو را یکی
نشان می‌داد.

راه درست‌ترش یک بُعد جدا (یا سلسله‌مراتب واحدها) است، ولی `org_unit` همین حالا
در حدود صد نقطه استفاده شده و هر کدام یک فرصت برای شکستنِ چیزی است که امروز کار
می‌کند. تصمیم صاحب محصول این بود که فعلاً همان رشته با یک جداکننده نوشته شود و
سامانه فقط *گزارش* را تفکیک کند.

پس این ماژول تنها جایی است که آن قرارداد را می‌داند. اگر روزی ستون واقعی اضافه
شود، همین‌جا عوض می‌شود و بقیهٔ کد دست نمی‌خورد — که دلیل وجودِ خودِ این فایل
است: قراردادِ پخش‌شده در ده جا، قرارداد نیست.

قرارداد
-------
«محل / واحد» — مثلاً «کارخانه / فروش». جداکنندهٔ خط‌تیره و خط‌تیرهٔ بلند هم
پذیرفته می‌شوند، چون آدم‌ها هر سه را تایپ می‌کنند و ردکردنِ دوتاشان فقط دادهٔ
نصفه‌نیمه می‌سازد.

نبودِ جداکننده خطا نیست: یعنی سازمان یک محل بیشتر ندارد، که حالت پیش‌فرض است.
"""

#: به‌ترتیب امتحان می‌شوند؛ اولین یافته برنده است.
SEPARATORS = ("/", "—", " - ")

#: جداکنندهٔ استانداردِ خروجی — همانی که خودمان می‌نویسیم.
CANONICAL_SEPARATOR = " / "

#: سه محلی که سازمان دارد.
#:
#: تا امروز فهرستِ محل‌ها *استخراج‌شده* بود: هرچه در `org_unit`ها پیدا می‌شد.
#: نتیجه‌اش این بود که یک محل تا وقتی حتی یک نفر در آن ثبت نشده باشد، در هیچ
#: فیلتری وجود نداشت — و «مدرپ‌ها» که تازه اضافه شده، در هیچ‌کدام دیده نمی‌شد.
#:
#: حالا این سه همیشه هستند، و هرچه در داده باشد و این‌جا نباشد هم به فهرست
#: اضافه می‌شود. یعنی فهرست *شامل* واقعیت است، نه محدود به آن: دادهٔ قدیمی با
#: املای دیگر ناپدید نمی‌شود.
KNOWN_SITES: tuple[str, ...] = ("دفتر مرکزی", "کارخانه", "مدرپ‌ها")


def split_site(org_unit: str) -> tuple[str | None, str]:
    """(محل، واحد) — محل خالی یعنی جداکننده‌ای در کار نبوده."""
    for separator in SEPARATORS:
        if separator in org_unit:
            site, _, unit = org_unit.partition(separator)
            site, unit = site.strip(), unit.strip()
            # «/ فروش» یا «کارخانه /» نیمه‌کاره‌اند؛ همان رشتهٔ کامل بهتر از یک
            # محلِ خالی یا واحدِ خالی است.
            if site and unit:
                return site, unit
    return None, org_unit.strip()


def site_of(org_unit: str) -> str | None:
    return split_site(org_unit)[0]


def known_sites(org_units: list[str]) -> list[str]:
    """محل‌ها برای پرکردن فهرست فیلتر: سه محلِ شناخته‌شده، به‌علاوهٔ هرچه در داده هست.

    ترتیب عمدی است — سه محلِ رسمی اول می‌آیند و بقیه بعد از آن‌ها الفبایی. کسی
    که فیلتر را باز می‌کند دنبال یکی از آن سه است؛ املای قدیمیِ یک واحد نباید
    بالای فهرست بنشیند.
    """
    extra = sorted(
        {site for unit in org_units if (site := site_of(unit)) and site not in KNOWN_SITES}
    )
    return [*KNOWN_SITES, *extra]


def join_site(site: str | None, unit: str) -> str:
    """(محل، واحد) → همان رشته‌ای که در `org_unit` ذخیره می‌شود."""
    unit = unit.strip()
    site = (site or "").strip()
    return f"{site}{CANONICAL_SEPARATOR}{unit}" if site and unit else unit


def units_in_site(all_units: list[str], site: str) -> list[str]:
    """واحدهایی که زیر یک محل‌اند.

    تطبیق در پایتون و با همان `site_of`ی که همه‌جا استفاده می‌شود، نه با یک الگوی
    LIKE. الگوی LIKE یعنی قرارداد جداکننده دو بار نوشته شود، و همان‌جا بود که
    اولین بار شکست: مقدارِ واقعی «کارخانه / فروش» فاصله دارد و الگوی «کارخانه/%»
    هیچ‌چیز نگرفت. تعداد واحدهای متمایز ده‌ها است، پس خواندنشان ارزان‌تر از
    نگه‌داشتن دو نسخه از یک قانون است.
    """
    wanted = site.strip()
    return [unit for unit in all_units if site_of(unit) == wanted]
